public class Datatype {
    public static void main(String[] args) {
        int num1=10;
   System.out.println(num1);
    // numeric records
			byte no = 10; // 1 byte = 8 bit
            System.out.println(no);

			short no2 = 20;  // 2 byte = 16 bit
            System.out.println(no2);

			int no3 = 30;   // 4 byte = 32 bit
            System.out.println(no3);

			long no4 = 40;  // 8 byte = 64 bit
			System.out.println(no4);

			// decimal records
			float marks = 33.56f; // 4 byte
            System.out.println(marks);

			double salary = 500000.34; // 8 byte
			System.out.println(salary);


			//character
			char section = 'A';  // 2 byte
			System.out.println(section);
            
			//boolean 
			boolean haveidcard = true; // 1 byte  true false
			
			System.out.println(haveidcard);
}
    


}
